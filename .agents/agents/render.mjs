import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const roles = ['adversarial-author', 'adversarial-reviewer', 'senior-dev', 'senior-qa'];
const openCodeModels = readModels('.opencode');
const codexModels = readModels('.codex');
const outputs = [];

for (const role of roles) {
  const source = readFileSync(new URL(`${role}.md`, import.meta.url), 'utf8');
  const separator = /\r?\n\r?\n/.exec(source);
  if (!separator || separator.index === 0) {
    throw new Error(`${role}.md needs a description followed by a blank line and the role instructions.`);
  }
  const description = source.slice(0, separator.index).trim();
  const instructions = source.slice(separator.index + separator[0].length).trimEnd();
  if (!description || !instructions) {
    throw new Error(`${role}.md needs both a description and role instructions.`);
  }

  const adversarialRole = role === 'adversarial-author' || role === 'adversarial-reviewer';
  const openCode = openCodeModels[role] ?? {};
  const codex = codexModels[role] ?? {};
  outputs.push(
    [`.opencode/agents/${role}.md`, [
      '---',
      '# Generated by .agents/agents/render.mjs',
      `description: ${quote(description)}`,
      'mode: subagent',
      ...modelLines(openCode, ['model', 'variant'], ': '),
      'permission:',
      '  edit: allow',
      `  bash: ${adversarialRole ? 'deny' : 'allow'}`,
      '---',
      '',
      instructions,
      '',
    ].join('\n')],
    [`.codex/agents/${role}.toml`, [
      '# Generated by .agents/agents/render.mjs',
      `name = ${quote(role)}`,
      `description = ${quote(description)}`,
      ...modelLines(codex, ['model', 'model_reasoning_effort'], ' = '),
      `developer_instructions = ${quote(instructions)}`,
      ...(adversarialRole ? ['', '[features]', 'shell_tool = false'] : []),
      '',
    ].join('\n')],
  );
}

for (const [path, content] of outputs) {
  const destination = new URL(path, root);
  mkdirSync(new URL('.', destination), { recursive: true });
  writeFileSync(destination, content);
}

function readModels(directory) {
  return JSON.parse(readFileSync(new URL(`${directory}/agent-models.json`, root), 'utf8'));
}

function modelLines(settings, keys, separator) {
  return Object.entries(settings).map(([key, value]) => {
    if (!keys.includes(key) || typeof value !== 'string' || !value.trim()) {
      throw new Error(`Invalid model setting ${key}. Expected a non-empty string for ${keys.join(' or ')}.`);
    }
    return `${key}${separator}${quote(value)}`;
  });
}

function quote(value) {
  return JSON.stringify(value).replaceAll('\u007f', '\\u007f');
}
